    /// Selected style of the control.
    /// </summary>
    Selected,

    /// <summary>
    /// Disabled style of the control.
    /// </summary>
    Disabled,

    /// <summary>
    /// ReadOnly style of the control.
    /// </summary>
    ReadOnly
}