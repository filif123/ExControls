namespace ExControls;

/// <summary>
/// Type of style.
/// </summary>
public enum StyleType
{
    /// <summary>
    /// Normal style of the control.
    /// </summary>
    Normal,

    /// <summary>
    /// Hover style of the control.
    /// </summary>
    Hover,

