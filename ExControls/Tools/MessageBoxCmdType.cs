    /// Retry button.
    /// </summary>
    Retry = 3,

    /// <summary>
    /// Ignore button.
    /// </summary>
    Ignore = 4,

    /// <summary>
    /// Yes button.
    /// </summary>
    Yes = 5,

    /// <summary>
    /// No button.
    /// </summary>
    No = 6,

    /// <summary>
    /// Close button.
    /// </summary>
    Close = 7,

    /// <summary>
    /// Help button.
    /// </summary>
    Help = 8,

    /// <summary>
    /// Try Again button.
    /// </summary>
    TryAgain = 9,

    /// <summary>
    /// Continue button.
    /// </summary>
    Continue = 10
}
