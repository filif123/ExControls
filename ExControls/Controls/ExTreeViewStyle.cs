namespace ExControls;

/// <summary>
/// Windows theme of <see cref="ExTreeView" />.
/// </summary>
public enum ExTreeViewStyle
{
    /// <summary>
    /// Default theme of the tree view.
    /// </summary>
    Default,

    /// <summary>
    /// Explorer theme (as in Windows Explorer).
    /// </summary>
    Light,

    /// <summary>
    /// Dark Explorer theme.
    /// </summary>
    Dark,

    /// <summary>
    /// No theme - the classic look with plus/minus signs.
    /// </summary>
    Old
}
